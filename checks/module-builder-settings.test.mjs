import assert from 'node:assert/strict';
import {moduleStartCandidates} from '../public/module-builder-settings.js';
import {moduleConfiguration} from '../public/catalog-model.js';
import {saveSofa} from '../public/sofa-model.js';
const common={moduleSeries:'Test',active:true,stock:4,unavailable:0,price:100,weekPrice:200,monthPrice:300,moduleWidth:74};
const end={...common,id:'end',moduleRole:'end',rentalRequiredQuantity:2,rentalStartQuantity:2};
const mid={...common,id:'mid',moduleRole:'middle',rentalStartQuantity:1};
const products=[end,mid],selection=moduleStartCandidates(products,null,{end:2})[0];
assert.deepEqual(selection,{end:2,mid:1});
assert.equal(moduleConfiguration('Test',selection,{},products).valid,true);
assert.equal(moduleConfiguration('Test',{end:1,mid:1},{},products).valid,false);
assert.equal(saveSofa([],{},products,{id:'bad',series:'Test',selection:{mid:1}}),null);
const one=saveSofa([],{},products,{id:'one',series:'Test',selection});
assert.equal(one.cart.end,2);assert.equal(moduleConfiguration('Test',selection,{},products).price,300);
const two=saveSofa(one.setups,one.cart,products,{id:'two',series:'Test',selection});
assert.equal(two.cart.end,4);
assert.equal(saveSofa(two.setups,two.cart,products,{id:'three',series:'Test',selection}),null);
const optional=[{...end,rentalRequiredQuantity:0,rentalStartQuantity:0},mid];
assert.deepEqual(moduleStartCandidates(optional,null,{end:2})[0],{end:0,mid:1});
assert.equal(moduleConfiguration('Test',{mid:1},{},optional).valid,true);
const legacy=[{...common,id:'left',moduleRole:'left',moduleRequired:true},{...common,id:'right',moduleRole:'right',moduleRequired:true}];
assert.equal(moduleConfiguration('Test',{left:1},{},legacy).valid,false);
assert.equal(moduleConfiguration('Test',{left:1,right:1},{},legacy).valid,true);
console.log('Rental defaults, mandatory ends, optional ends, legacy requirements, price and shared stock passed.');

const {validateCatalog}=await import('../server/catalog.mjs');
const raw=ps=>ps.map(p=>({...p,name:p.id,category:'Sofaer',material:'',description:'',image:'/assets/test.webp',type:'sofa',color:'#ffffff',isPackage:false,components:[],rentalPricingMode:'manual'}));
const saved=validateCatalog(raw(products));
assert.equal(saved.find(p=>p.id==='end').rentalRequiredQuantity,2);
assert.equal(saved.find(p=>p.id==='mid').rentalStartQuantity,1);
assert.throws(()=>validateCatalog(raw([{...end,rentalStartQuantity:1},mid])),/Startantallet/);
assert.throws(()=>validateCatalog(raw([{...end,rentalRequiredQuantity:3,rentalStartQuantity:3},mid])),/modulantall/);
const {receiptSofaLines}=await import('../server/receipt-sofas.mjs');
const lines=[{id:'end',quantity:2,total:200},{id:'mid',quantity:1,total:100}];
const receipt=receiptSofaLines(lines,[{id:'test',series:'Test',selection}],products);
assert.equal(receipt.reduce((s,p)=>s+p.total,0),300);assert.equal(receipt[0].group.type,'sofa');
assert.throws(()=>receiptSofaLines([{id:'mid',quantity:1,total:100}],[{id:'test',series:'Test',selection:{mid:1}}],products));
