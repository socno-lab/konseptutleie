import assert from 'node:assert/strict';
import {selectionDraft} from '../public/catalog-model.js';
const bed={id:'bed',active:true,stock:60,unavailable:0,type:'generic',relatedAddOns:['single','double']};
const single={id:'single',active:true,stock:60,unavailable:0};
const double={id:'double',active:true,stock:60,unavailable:0};
const chair={id:'chair',active:true,stock:4,unavailable:0};
const products=[bed,single,double,chair];
assert.deepEqual(selectionDraft({},products,'chair',3),{chair:3});
assert.equal(selectionDraft({chair:3},products,'chair',2),null);
assert.deepEqual(selectionDraft({},products,'bed',2,'double',1),{bed:2,double:1});
assert.equal(selectionDraft({},products,'bed',61,'single',1),null);
assert.equal(selectionDraft({double:60},products,'bed',2,'double',1),null);
assert.equal(selectionDraft({},products,'bed',1,'chair',1),null);
assert.equal(selectionDraft({},products,'bed',1.5),null);
assert.equal(selectionDraft({},products,'bed',1,'single',0),null);
const basket={chair:3};selectionDraft(basket,products,'chair',2);assert.deepEqual(basket,{chair:3});
const sofa={id:'sofa',type:'sofa',active:true,stock:4,unavailable:0};const pack={id:'pack',isPackage:true,active:true,components:[{id:'sofa',quantity:1}]};
assert.deepEqual(selectionDraft({sofa:3},[sofa,pack],'pack',2),{sofa:1,pack:2});
console.log('Product quantities, independent add-on quantities, atomic stock limits and package replacement passed.');
