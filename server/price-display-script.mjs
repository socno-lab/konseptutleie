import {readFile,writeFile} from 'node:fs/promises';
import assert from 'node:assert/strict';
const root=new URL('../',import.meta.url);
// The classic entry point uses the same source model and controller as tests.
// Keep it self-contained so saved prices apply before deferred modules load.
export async function priceDisplayScript(){
 const [model,markup,controller]=await Promise.all(['public/price-display-model.js','public/price-display-markup.js','public/price-display.js'].map(file=>readFile(new URL(file,root),'utf8')));
 assert.doesNotMatch(model,/^import /m,'The price model must remain dependency-free for first paint.');
 const imports=controller.match(/^import .*;\n/gm)||[];
 assert.equal(imports.length,2);assert.match(imports[0],/from '\.\/price-display-model\.js\?[^']+';/);assert.match(imports[1],/from '\.\/price-display-markup\.js\?[^']+';/);
 const body=model.replace(/^export /gm,'')+'\n'+markup.replace(/^export /gm,'')+'\n'+imports.reduce((source,line)=>source.replace(line,''),controller);
 assert.doesNotMatch(body,/^(?:import|export) /m);
 return '// Generated from price-display-model.js, price-display-markup.js and price-display.js.\n// Regenerate with server/price-display-script.mjs; do not edit this file.\n(()=>{\n'+body+'\n})();\n';
}
export async function writePriceDisplayScript(){await writeFile(new URL('public/price-display-first.js',root),await priceDisplayScript());}
export async function assertPriceDisplayScript(){assert.equal(await readFile(new URL('public/price-display-first.js',root),'utf8'),await priceDisplayScript(),'Price first-paint script is stale; regenerate it from the source model/controller.');}
