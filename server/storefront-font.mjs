import {readFile,writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import path from 'node:path';

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
export const storefrontFontHref='/storefront-font.css?v=fontfirstpaint20261026';
export const storefrontFontSource='/fonts/dm-sans-latin-v17.woff2';

export async function storefrontFontCss(base=root){
 const [css,font]=await Promise.all([readFile(path.join(base,'public/style.css'),'utf8'),readFile(path.join(base,'public',storefrontFontSource))]);
 const face=[...css.matchAll(/@font-face\s*\{[\s\S]*?\}/g)].map(match=>match[0]).find(value=>value.includes('url('+storefrontFontSource+')'));
 if(!face)throw Error('DM Sans Latin mangler i det godkjente stilarket.');
 if(font.toString('ascii',0,4)!=='wOF2')throw Error('DM Sans-kilden er ikke WOFF2.');
 // Keep the approved font bytes and visual descriptors. The blocking stylesheet
 // carries all bytes; block only the brief local decode to avoid a fallback flash.
 return '/* Generated by node server/storefront-font.mjs --write.\n * Exact DM Sans Latin v17 font; SIL Open Font License: /fonts/dm-sans-OFL.txt.\n * Source and attribution remain in /fonts/SOURCES.json.\n * Block fallback during local decode; font bytes require no additional request. */\n'+face.replace('url('+storefrontFontSource+')','url(data:font/woff2;base64,'+font.toString('base64')+')').replace(/font-display:\s*swap;/,'font-display: block;')+'\n';
}

export async function assertStorefrontFont(base=root){
 const actual=await readFile(path.join(base,'public/storefront-font.css'),'utf8');
 if(actual!==await storefrontFontCss(base))throw Error('Fontstilarket er utdatert. Kjør node server/storefront-font.mjs --write.');
}

if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url)){
 if(process.argv[2]==='--write')await writeFile(path.join(root,'public/storefront-font.css'),await storefrontFontCss());
 else await assertStorefrontFont();
}
