import assert from 'node:assert/strict';
import {readFile,writeFile} from 'node:fs/promises';
const root=new URL('../',import.meta.url);

// Bundle the exact canonical tariff function and date validator, without a
// second pricing implementation or the unrelated basket/UI dependency graph.
export async function rentalPeriodScript(){
 const paths=['public/catalog-model.js','public/rental-dates.js','public/price-display-model.js','public/rental-period-display.js','public/detail-price-model.js','public/rental-selection-summary.js','public/rental-period-first-paint.js'];
 const [catalog,dates,prices,model,selection,summary,controller]=await Promise.all(paths.map(path=>readFile(new URL(path,root),'utf8')));
 const rate=catalog.slice(catalog.indexOf('export function ratePlan('),catalog.indexOf('export function planText('));
 assert.match(rate,/^export function ratePlan\(/);assert.match(rate,/\n}\n$/);
 const flatten=source=>source.replace(/^import .*;\n/gm,'').replace(/^export /gm,'');
 assert.doesNotMatch(dates,/^import /m);assert.doesNotMatch(prices,/^import /m);
 const body=[rate,dates,prices,model,selection,summary,controller].map(flatten).join('\n');
 assert.doesNotMatch(body,/^(?:import|export) /m);
 return '// Generated from canonical rental pricing, dates and rental-period display sources.\n// Regenerate with server/rental-period-script.mjs; do not edit this file.\n(()=>{\n'+body+'\n})();\n';
}
export async function writeRentalPeriodScript(){await writeFile(new URL('public/rental-period-first.js',root),await rentalPeriodScript());}
export async function assertRentalPeriodScript(){assert.equal(await readFile(new URL('public/rental-period-first.js',root),'utf8'),await rentalPeriodScript(),'Rental period first-paint script is stale; regenerate it from its source model/controller.');}
